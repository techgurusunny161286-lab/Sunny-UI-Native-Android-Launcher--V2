// Helper to get persisted community store themes (with user-uploaded themes merged)
export const getCommunityThemes = (): CommunityTheme[] => {
  try {
    const customUploadsStr = localStorage.getItem('sol_community_uploads');
    if (customUploadsStr) {
      const customUploads: CommunityTheme[] = JSON.parse(customUploadsStr);
      return [...customUploads, ...INITIAL_COMMUNITY_THEMES];
    }
  } catch {}
  return INITIAL_COMMUNITY_THEMES;
};

// Helper to save a new community theme upload
export const uploadThemeToCommunity = (theme: CommunityTheme): CommunityTheme[] => {
  try {
    const existing = getCommunityThemes();
    const customUploadsStr = localStorage.getItem('sol_community_uploads');
    const customUploads: CommunityTheme[] = customUploadsStr ? JSON.parse(customUploadsStr) : [];
    const updatedCustom = [theme, ...customUploads];
    localStorage.setItem('sol_community_uploads', JSON.stringify(updatedCustom));
    return [theme, ...existing];
  } catch {
    return [theme, ...INITIAL_COMMUNITY_THEMES];
  }
};

// Helper to get DIY Themes saved locally by the user
export const getSavedDIYThemes = (): DIYTheme[] => {
  try {
    const diyStr = localStorage.getItem('sol_diy_themes');
    if (diyStr) {
      return JSON.parse(diyStr);
    }
  } catch {}
  return [];
};

// Helper to save a DIY theme
export const saveDIYTheme = (diyTheme: DIYTheme): DIYTheme[] => {
  try {
    const existing = getSavedDIYThemes();
    const updated = [diyTheme, ...existing.filter((t) => t.id !== diyTheme.id)];
    localStorage.setItem('sol_diy_themes', JSON.stringify(updated));
    return updated;
  } catch {
    return [diyTheme];
  }
};

// Helper to delete a DIY theme
export const deleteDIYTheme = (id: string): DIYTheme[] => {
  try {
    const existing = getSavedDIYThemes();
    const updated = existing.filter((t) => t.id !== id);
    localStorage.setItem('sol_diy_themes', JSON.stringify(updated));
    return updated;
  } catch {
    return [];
  }
};
